        [KernelFunction, Description("コマンドラインによる起動")]
        public string Get5_23()
        {
            return """
　Windowsであっても、以下の局面でコマンドラインを活用することができます。
	・ショートカットのプロパティにおける“リンク先”欄の記述
	・“アプリケーションの関連付け”による定義
	・[スタート]→[ファイル名を指定して実行]による起動
	・コマンドプロンプトからの起動

　■コマンドラインによる起動では、以下の様な引数を与えることが可能です。
