        [KernelFunction, Description("マニュアル表示")]
        public string Get5_24()
        {
            return """
　「ファイル(F)」→「マニュアル表示(H)」の選択で、専用ビューアが起動します。
　このビューアはインクリメンタルサーチの機構を備えています。そして、その検索
　結果とマニュアル本文を、同一ウィンドウ上で切替えながら閲覧できるよう、以下
　の２つのモードを用意しています。（括弧内はラインカーソルの色です）

　　通常モード ： Readme.txtの本文を単純に表示する　（薄水色）
　　検索モード ： 検索に掛かった行のみを列挙表示する（若草色）

　■インクリメンタルサーチ
　・所望の検索文字を打鍵し始めると、即座に「検索モード」に移行します。
　　「検索モード」では検索された文字列が赤く強調され、マウスに追従するライン
　　カーソルが薄水色から若草色に変化します。そして文字を打ち進めるにつれて、
　　リアルタイムに該当行が絞込まれていきます。

　　(注)行内で一番最初に出現する合致文字列のみが強調表示されます。
	一行内に複数の合致があっても、２番目以降は強調されません。
	また、あくまでも行単位のサーチであるため、途中改行された単語は検索対
	象から除外されます。

　・「検索モード」で該当行をダブルクリックすると「通常モード」に復帰します。
　　その際、極力該当行をウィンドウ上部中段に位置付けるように展開表示します。
　・「通常モード」で再度ダブルクリックすると、直前の検索文字列で「検索モード」
　　に移行します。移行の際、マウスの位置も含めて可能な限り直前の検索表示状態
　　を再現します。
　・「検索モード」と「通常モード」がダブルクリックによって交互に切替わるため、
　　それを繰返すことで、検索された各内容を順次閲覧していくことができます。
　・検索文字はスペースやタブも対象になります。また、行頭に添えられた行番号も
　　本文と同等に扱われ検索対象になります。したがって、検索文字列に行番号を与
　　えれば該当行に容易に到達できます。

　　(注)左上角の[□]ボタンは、英字の大文字と小文字を同一視するか、区別するか
	を切替えるトグルスイッチです。通常は同一視で検索し、押下すると[■]に
	変化し、区別して検索するようになります。なお、全角／半角は常に同一視
	されます。

　■検索文字列の抽出
　・任意のカラムをマウスでスイープすると、選択された文字が検索文字列として採
　　用され、その場で「検索モード」に反映されます。
　・このスイープ機構は、「通常モード」「検索モード」のどちらのモードでも利用
