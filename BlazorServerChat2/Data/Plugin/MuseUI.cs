　　反映します。これにより、調整した演奏会場で各楽器やドラムがどの様に響くか
　　を確認することができます。

""";
        }

        [KernelFunction, Description("メンバー情報の確認")]
        public string Get5_6()
        {
            return """
　「機能(G)」→「メンバー情報(M)」の選択で、鍵盤上に表示される各メンバーの色
　を確認できます。データがロードされている状態であれば、その演奏に参加してい
　るメンバーに◆印が付き、そのメンバーの使用楽器が表示されます。演奏途中で楽
　器の持替えが起ると、リアルタイムに表示が切替わります。更に、バリエーション
　指定されている楽器には“／数字”という形式で、楽器名にバリエーション番号が
　添えられます。

　■演奏メンバーの制御
　・左端に◆印の付いているメンバーをマウス左クリックすると、印が◇に変り、そ
　　のメンバの演奏だけを止めさせることができます。再度クリックすると◆に戻り
　　演奏を再開します。また、マウスの右クリックで、すべての◆印を一斉に切替え
　　ることができます。

　・この機能は、Museデータ作成過程において各メンバーを分離してデバッグしたり、
　　楽器の音色を微調するのに便利です。また、主旋律を止めて伴奏だけにすれば、
　　カラオケソフトとしても活用できます。

　　(注)メンバー毎のON/OFF状態は、譜面モニタやエクスポート(MIDI,WAVE,PDF)に
	も反映します。

　・メンバー毎のON/OFF機構はキーボードからも行えます。それぞれのメンバーＩＤ
　　(A-O,Z)の押下でＯＦＦになり、[SHIFT]キーの併用でＯＮに復帰します。すべて
　　の音を消す場合は [x] を、すべての音を出す場合は [SHIFT]＋[x] を押下して
　　ください。

""";
        }

        [KernelFunction, Description("フィンガー情報の確認")]
        public string Get5_7()
        {
            return """
　「機能(G)」→「フィンガー情報(F)」の選択で、現在ロードされているデータの最
　終的な属性値がフィンガー単位で表示されるウィンドウが出現します。ウィンドウ
　は、ヘッダー部、リスト部、フッター部で構成されています。

　■ヘッダー部
　　左上に表示されている分数は、分母が「総フィンガー数」を、分子が「ON状態の
　　フィンガー数」を表します。また、中央には曲尾におけるテンポ値(%)が、右側
　　には表示するメンバー属性を切り替えるためのコンボボックスがあります。

　　ヘッダー部テンポ表示エリアのクリック、あるいは[P]キー押下により、ドラム
　　以外のフィンガー行を巡回し、標準オクターブ(o4)から外れたフィンガーがあれ
　　ば、その行にジャンプします。また、検出の際はウィンドウタイトルに●印が付
　　きます。この●印は、以下の場合にクリアされます。
	- 標準オクターブのみの状態で再検索した場合
	- ヘッダー部フィンガー数エリアをクリックした場合
	- フィンガー情報ウィンドウを一旦閉じて再起動した場合

　　(注)初期化ファイル(muse.ini)の“OCT指定”で、Museデータロード時に標準オク
	ターブの自動チェックを実施できます。なお、フィンガー情報が表示されて
	いない場合は、OCT指定がONであってもチェックしません。

　■リスト部
　　各フィンガーが曲尾の段階で保持している音部記号、オクターブ、強弱値などの
　　状態を確認できます。また、各フィンガーが属するメンバーの主な属性値も右端
　　に表示されます。表示するメンバー属性は上部のコンボボックスで切替えること
　　ができます。

　■フッター部
　　リスト上で選択されているフィンガーが属するメンバーの波形加工値(R= W= Q=)
　　や、調性および移調(\ T y)、出音・止音のタイミング(p q)、音名タイプ(x)、
　　アクセント値(w)などの曲尾状況が表示されます。なお、フッターの右クリック
　　でデータをリロードすることができます。データの手直しと確認の際に便利です。

　■フィンガー単位の演奏制御
　・１つのメンバーに複数のフィンガーが存在する場合、特定のフィンガーだけを取
　　り出したい場合があります。それを可能にするのが、フィンガー毎のON/OFF機構
　　です。リスト行頭の“#”部分を左クリックすることで、その行のフィンガーが
　　ON/OFFします。OFFになると“#”記号が非表示となります。

　・全フィンガーを一気にON/OFFしたい場合は、リストを右クリックします。なお、
　　リストの右側エリア(メンバー属性表示領域)を右クリックした場合は、その位置
　　のメンバーに属するフィンガーのみが一括してON/OFFされます。

　　(注)フィンガー毎のON/OFF状態は、譜面モニタやエクスポート(MIDI,WAVE,PDF)に
	も反映します。ただし、フィンガーをOFFにしても、そのフィンガーに対する
	メンバー属性は、ON状態が維持されます。メンバー属性もOFF状態にしたい場
	合は、メンバー情報のON/OFF機構を利用してください。

　・フィンガー毎のON/OFF機構はキーボードからも行えます。[x]を押下すると、リス
　　ト上の選択行フィンガーのON/OFFが切り替わります。また、[CTRL]キーを併用し
　　て[x]キーを押下すると、該当フィンガーが属するメンバーのすべてのフィンガー
　　がON/OFFします。[SHIFT]を併用すると、全フィンガーが一気にON/OFFします。

　■キーによるフィンガー選択
　　メンバーＩＤとして[A]～[O],[Z]のキーを押下すると、該当行にジャンプします。
　　連続入力で同一メンバー内をトグルシフトします。[SHIFT]キーの併用でトグルの
