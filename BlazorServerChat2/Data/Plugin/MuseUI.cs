	ム音が鳴らない音源もあります。

　・音名表示欄の上にノート番号が表示されます。10進表記に加え、鍵括弧で16進表
　　記も示されます。DATAコマンドを使用する場合にご活用ください。なおスクロー
　　ルバーでピッチを変化させ、その音を確認することもできます。ピッチを標準の
　　U0 に復帰したい場合は、ピッチ値が表示されているボタンを押下してください。

