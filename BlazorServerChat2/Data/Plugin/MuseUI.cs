　・各ダイアログ右下の[波形加工⇒]ボタン押下で、波形加工ダイアログが出現しま
　　す。波形加工のパラメータにより、音色がどの様に変化するか確認できます。各
　　特性パラメータをスクロールバーで調整すると、波形のイメージ図が変化しその
　　傾向を目視で確認できます。

　・スクロールバーを移動すると、その都度、新しい特性値での発音が起こります。
　　ダイアログ下部にある残響(R)、揺らぎ(W)、コーラス(Q)、および強弱(v)のスラ
　　イダーにて、これらのエフェクトによる音質変化確認も可能です。

　・最下端に並んでいる“初期化”[R][W][Q]の各ボタンは、各特性やエフェクトを
　　初期状態に戻す機能を持っています。また、[COPY]ボタンを押下すると、その時
