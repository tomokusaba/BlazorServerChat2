	選択時に演奏を開始するか否か(LGP)を、制御することができます。
	詳細は“(19) 初期化ファイルによる指定”を参照してください。

　■履歴ファイルのアルバム化
　・履歴曲は最新アクセス曲で順次更新されますが、もしお気に入りの曲があり、固
　　定的に記憶させておきたい場合は、直接履歴ファイルを編集する事でそれが可能
　　となります。“履歴”と言うよりもむしろ“アルバム”と言った方が相応しい機
　　構です。履歴ファイル編集は任意のエディタ(メモ帳等)で行ってください。履歴
　　ファイルに記述ミスがある場合はエラーは発生せず、その行は無視されます。

　　(注)Museデータへのパスは、絶対パス／相対パスどちらも使用できます。
	相対パスの場合は、muse.exeの存在フォルダが基点となります。

　・履歴ファイルをアルバム化する方法は至って簡単です。自動的に生成された履歴
　　行の要所々々に、アスタリスク(*)で始る行を挿入し、そこにタイトル名を記述
　　するだけです。曲の順番も自由に移動できます。履歴メニューでは、タイトルを
　　階層フォルダとしたグループが形成され、その配下のログ曲は更新対象にならず
　　固定的に保持されます(曲データ行)。アスタリスク１つで無タイトルのグループ
　　は通常の履歴ログとして扱われ、ロードする度に更新されます(ログ行)。

	*ポップス			 　← タイトル行
		>D:\MuseData\Sample01.mus　┐
		>D:\MuseData\Sample02.mus　│ 曲データ行
		>D:\MuseData\Sample03.mus　┘
	*ゲーム音楽			 　← タイトル行
		>D:\MuseData\Sample04.mus　┐
		>D:\MuseData\Sample05.mus　│ 曲データ行
		>D:\MuseData\Sample06.mus　┘
	*クラシック			 　← タイトル行
		>D:\MuseData\Sample07.mus　┐
		>D:\MuseData\Sample08.mus　│ 曲データ行
		>D:\MuseData\Sample09.mus　┘
	*
		>D:\MuseData\Sample00.mus　┐
		>D:\MuseData\Sample11.mus　│ログ行
		>D:\MuseData\Sample12.mus　┘
			・
			・
			・

　　(注)履歴ファイルはMuseを終了させるタイミングで上書きされます。履歴ファイ
	ルを編集する場合は、一旦Museを終了してから実施してください。

　・タイトル行をひとたび設定すれば、以降はエディタでの編集が不要となり、履歴
　　履歴メニュー上のマウス操作で、手軽に曲データ行をメンテナンスする事ができ
　　るようになります。可能な操作は登録と除去の２つです。

	＜曲データ行を登録＞
	　　タイトル部を右クリックすると、現在ロードされている曲がタイトルの
	　　階層下に登録されます。パスの記録は絶対パスで行われます。

	＜曲データ行を除去＞
	　　曲データ部を右クリックすると、その曲を除去します。アルバムからの
	　　リンクを除去するだけで、データそのものを消去する訳ではありません。

　・履歴ファイルの編集で、階層を多段にすることも可能です。
　　例えば以下の様な階層を履歴ファイルで定義する場合について解説します。
　　黒丸(●)がタイトル行、二重丸(◎)が曲データ行とします。
　　音楽とは関係ない、お酒の例で恐縮です(笑)。

		┃
