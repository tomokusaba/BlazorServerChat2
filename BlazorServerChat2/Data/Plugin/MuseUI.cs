        [KernelFunction, Description("楽器やドラムの試聴")]
        public string Get5_5()
        {
            return """
　「機能(G)」→「楽器の試聴(P)」および「ドラムの試聴(Z)」の選択で、各音色を
　確認できるダイアログが出現します。対象となる音源名称はウィンドウタイトルに
　表示されています。音源は任意のタイミングで、メニュー「音源(V)」にて切替え
　ることができます。なお、発音タイミングで当該の情報がクリップボードに出力さ
　れます。

　　(注)試聴系ダイアログを起動している最中は、データの演奏は行えません。
	また「楽器の試聴」と「ドラムの試聴」を同時に起動することもできません。
	片方の起動中にもう片方をメニュー選択すると、強制的に入れ替わります。

　■発音の仕方
　・任意のボタンを押下することで発音が開始されます。音を止めるにはマウスの右
　　ボタンを任意の位置でクリックするか、[ESC]キーの押下、あるいは[■音止]ボ
　　タンを押してください。また、[♪]ボタンで発音を再開できます。

　・それぞれの試聴ダイアログには、[x0]の音名ボタンがあり、これを押下すると音
　　名の表示形式を切替えることができます。

　■楽器の試聴
　・音程のスクロールバーは、左右の三角ボタンで半音ずつ、スライド領域の押下で
　　１オクターブずつ変化します。音程が表示されているボタンを押下すると、中央
　　のドに復帰し、発音が停止します。

　・数字キー[1]～[9][0][-][^][\]の押下で、１０刻みのバリエーション変更ができ
　　ます。[0]で100番台、[-]で110番台、[^]で120番台となります。[\]は0番台です。
　　なお、キー押下によるバリエーション変更を行うとフォーカスがスクロールバー
　　に移動するため、その場で[←][→]キーを押下すると、１刻みのバリエーション
　　変更が可能です。

　　(注)音源によっては、すべてのバリエーションをサポートしていません。サポー
	トされていないバリエーションが指定された場合は、各々の音源仕様により、
	標準音が鳴る場合と、無音となる場合があります。

　・ローマ字の打鍵で、MuseLoid用のバリエーション番号がセットされます。処理効
　　率のため部分的に変則的なローマ字セットになっています。具体的な組合わせは、
　　“(10) サウンドフォントの活用”の ≪ MuseLoid配列 ≫ を参照してください。
　　なお、この配列範囲のバリエーションが選ばれている時は、スクロールバー右肩
　　に、該当の発声文字が表示されます。

　■ドラムの試聴
　・下辺に並んでいる選択ボタンで、ドラムセットを選ぶことができます。ボタン名
　　称に黒丸●が付く場合は、Standardセットと異なる音色であることを示します。
　　Classic や Ethnic、Asia、SFXのドラムセットは、ボタン名称自体が切替ります。

　　(注)MIDI音源によっては、Ethnic や Asiaなどのドラム音色が使用できない機種
	があります。この場合、直前に選んでいたドラムセットが維持され、結果と
