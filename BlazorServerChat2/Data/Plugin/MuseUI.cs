		┃　　┣━━◎カクテル.mus
		┃　　┣━━◎まむし酒.mus
		┃　　┣━━◎梅酒.mus
		┃　　┃

		　　　↑    ↑
		      (*)   (**)

　　上記の様な多段の階層を実現したい場合、タイトル行にアスタリスクを連ねる事
　　で定義します。本例では、お酒を醸造酒・蒸留酒・混成酒の３つに大分類し(*)、
　　更に醸造酒を、果実系と穀物系に分類しています(**)。

	*醸造酒
	**果実系
		>D:\MuseData\ワイン.mus
		>D:\MuseData\シードル.mus
