        [KernelFunction, Description("Museファイルのロード")]
        public string Get5_1()
        {
            return """
			　「ファイル(F)」→「開く(O)」の選択で出現するダイアログで、Museデータを読込
			　みます。Museデータは譜面を文字で表現するテキストファイルですが、一般のテキ
			　ストファイルと区別するため、ファイル拡張子を.musにすることを推奨します。

			　　(注)Museのショートカットを作成することで、ロード用ダイアログで初期表示す
				るフォルダを制御できます。ショートカットのプロパティで「作業フォルダ」
				の欄に、表示させたいフォルダを指定してください。

			　■Museデータの書式は前章で規定された文法に従っていなければなりません。なお、
			　　ファイルの形式は、SHIFT-JISに加え、ユニコード(UTF-8/UTF-16)にも対応してい
			　　ます。UTF-16はリトルエンディアン、ビッグエンディアン共可能で、サロゲート
			　　ペアにも対応しています。また、各ファイルの文字コードは自動判別されます。

			　　(注)BOMが付いていないUTF-8は、ファイル冒頭に「全角のセント“￠”」を書い
				ておいてください。これによりS-JISとの自動判別が可能となり、文字化けを
				防ぐことができます。なお、全角文字は演奏データとしては無視されるため、
				S-JISやUTF-16のファイル冒頭に“￠”が書かれていても支障はありません。

			　■ロード時に文法のチェックが行われ、エラーがあるとその内容とMuseファイル上
			　　の行番号をダイアログで知らせます。うまくロードできると、ウィンドウのタイ
			　　トル部に“→ mm:ss”の形式で演奏総時間が表示されます。一方、エラーがある
			　　と“→ ×”の表示となり、演奏に移れません。エラーが起こると、対象の行番号
			　　がクリップボードに出力されます。(キーボード操作のロードの場合は、エラー内
			　　容も出力されます)

			　　(注)ウィンドウタイトルをダブルクリックすると、データの絶対パスを確認する
				ことができます。

			　■データを作成している過程で、ロードとエディットを頻繁に繰返すことを想定し、
			　　「ファイル(F)」→「リロード(L)」の機能を設けました。このメニューは選んだ
			　　だけで現在ロードされているファイルを再び読込むので、カット＆トライがより
			　　簡便に行えます。また「開く(O)」と異なり、シークバーを巻戻さないので、曲の
			　　ある部分をデバッグする時も位置決めが容易です。

			　■「ファイル(F)」→「データ編集(D)」の選択で、テキストエディタが起動し、現
			　　在ロードされているデータが表示されます。起動するエディタは拡張子(.txt)と
			　　関連付けられているアプリケーションです。

			　　(注)起動するエディタを明示的に指定したい場合は、初期化ファイル(muse.ini)
				の#EDや#EPの指定で行えます。詳細は“(19) 初期化ファイルによる指定”
				を参照してください。
			
			""";
        }

