		┃　　┣━━●焼酎
		┃　　┃　　┣━━◎麦焼酎.mus
		┃　　┃　　┣━━◎米焼酎.mus
		┃　　┃　　┗━━◎いも焼酎.mus
		┃　　┣━━◎ブランデー.mus
		┃　　┣━━◎ウィスキー.mus
		┃　　┗━━◎泡盛.mus
		┃
