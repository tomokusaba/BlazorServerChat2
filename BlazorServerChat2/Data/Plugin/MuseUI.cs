	*m　起動時に「メンバー情報」を表示します。
	*f　起動時に「フィンガー情報」を表示します。
	*s　起動時に「譜面モニタ」を表示します。
	*n　起動時に前回の音源選択を抑止します。(音源未選択で起動します)
