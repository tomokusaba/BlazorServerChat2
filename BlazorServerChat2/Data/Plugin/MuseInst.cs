	　　　　/0 の指定でスタッカート調整も止音調整も行わない指定となる。
	　　（絶対指定）
	　　　　スラッシュ“/”に、^あるいは~を添えて更に音長を与える。
	　　　　発音に対し、その音長分の増減が起こる。
