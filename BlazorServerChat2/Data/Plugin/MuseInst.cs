	休符“_”も音名の一種と見なす。

　②音長表現（省略可能）

	　[音長値 + 付点] + [演算記号] + ... +　[スタッカート]
	└┬─────────────────┘
	　└→ 演算記号で接続し数式風に記述可能

	[音長値]
	　0,1,2,4,8,16,32,64 の８つの数値の内の１つ。
	　ゼロ音長は、演奏を無効化する。
	　ゼロ音長であっても、省略音長および再現表記の記憶が行われる。
