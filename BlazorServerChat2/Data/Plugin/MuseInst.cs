　①音名表現
	音階記号と臨時記号からなる。
	音階記号は、音名タイプ(x)に従った音名英字の内の１つ。
	臨時記号は、+ が♯、- が♭、= がナチュラルを表す。
	また、++でダブルシャープ、--でダブルフラットを表す。
	臨時記号は、常に調性“\”に優先して作用する。
