	[付点]
	　ピリオド“.”で表す。
	　複付点の場合は“..”とピリオドを２つにする。
	　３つ以上のピリオドは不可。
	　音長値を記述せずに付点のみ記述することはできない。

	[微分音長]
	　[音長値＋付点]の位置に、iに添えた1～960の数値により表現。
	　i1 が最小分解能であり、６４分音符の１／６０の音長を表す。
	　数値はその倍率を意味し、i60 で６４分音符の音長を表現する。
	　微分音長には付点を添えることはできない。

	[演算記号]
	　３つの記号(^加算　~減算 `乗算)で表す。
	　加減算記号の記述により[音長値＋付点]をいくつでも連ねられる。
	　乗算記号は、加減算記号より優先して演算される。
	　乗算記号直後の数字は乗算倍数であり、音長ではない。
	　乗算倍数を乗算記号で連続記述すると、乗算倍率自体が乗算される。

