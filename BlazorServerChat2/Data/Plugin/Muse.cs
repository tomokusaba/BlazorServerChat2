	[KernelFunction, Description("音符の連結")]
	public string Get2_18()
	{
		return """
;　例えば、四分音符とそれに続く三連符の初音との間がタイになっている場合、加算
;　音長でそのタイを記述することはできません。その様な場合は“&”指定を利用し
;　ます。“&”指定は、連続する同音階の音符を切れ目なく演奏させる指定です。
```
	%125 \=
	d4 & ( d m s )4 _2	← 初音がタイ接続されている場合
	( s m d )4 & d4 _2	← 終音がタイ接続されている場合
```
;　連符内に記述することもできます。
```
	d4 ( & d r m f s & s & s f m r d  & )1 d4 _2
```
;　この“&”指定は加算記号での表記よりも本来のタイの記述に近いと言えます。
;　和音やコードの連結も可能であり、その場合は互いの構成音の内音階の等しい音を
;　連結します。
```
	[ d m s ] & [ d f l ]	← ドの音だけがタイでつながる
	[ d m s ] & m        	← ミの音がタイでつながる
	s & [ d m s ]        	← ソの音がタイでつながる
```
;　ただし、和音内の要素音同士に連結記号“&”を記述しても効果は現れません。
;　和音内で音長を連結したい場合は、加算記号“^”で表現してください。
;
;	[ d8 & d32 m2 s2 ]4	← エラーにはならないが連結はしない。
;	[ d8^32    m2 s2 ]4	← ８分音符＋３２分音符の長さが与えられる。
;
;　和音内に“&”が記述された場合、“&”記号の直前の音符が、その和音の次に続く
;　音符や和音と連結対象となります。以下は和音同士の連結例です。
;
