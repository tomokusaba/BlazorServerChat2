    public string Get2_18()
    {
        return """
;　例えば、四分音符とそれに続く三連符の初音との間がタイになっている場合、加算
;　音長でそのタイを記述することはできません。その様な場合は“&”指定を利用し
;　ます。“&”指定は、連続する同音階の音符を切れ目なく演奏させる指定です。
```
