	[KernelFunction, Description("スコア譜とパート譜の混在")]
	public string Get4_9()
	{
		return """
;　テンポ値が添えられていない単独の“%”指定を利用すると、必然的にスコア風の
;　記述をすることになります。しかし例えば楽曲部分だけをスコア譜で記述し、歌詞
;　の部分はパート譜で記述したいといった場合も多々あります。この様な場合は“%”
;　の後にメンバー記号(A～O,Z)を添えてください。添えられたメンバーに対してのみ、
;　強制タイミング合せの機構が働く様になります。これにより、スコアとパートの楽
;　譜記述を混在させることができます。
;
;　“%”に添えるメンバー記号は、複数列挙することが可能です。( 例 %ABC )
;　その場合、列挙したメンバー内で、最も先まで音符のある位置まで休符が挿入され、
;　それらのメンバーだけが、その位置に整列します。
;　以下は、ＡＢＣメンバーをスコア譜で、Ｄメンバーをパート譜で記述する例です。
;
;	#A0 |①---------->|
;	#B0 |②------------------------>|
;	#C0 |③----------------->|
;
;	%ABC				←─●ここでABCのタイミングを合せる
;
;	#A0 |④-------------->|
;	#B0 |⑤-------------->|
;	#C0 |⑥-------------->|
;
;	#D0 |⑦------------->|		←┬●この部分はパート譜で記述
;	#D0 |⑧------------------->|	←┘
;
;　すると、メンバーＡＢＣにだけに整列のための休符が与えられ、実際の演奏は以下
;　の様になります。
;
;					 ●メンバーABCはこの位置に整列
;	                                 ↓
;	#A0 |①---------->|     休符    |④-------------->|
;	#B0 |②------------------------>|⑤-------------->|
;	#C0 |③----------------->| 休符 |⑥-------------->|
;	#D0 |⑦------------->|⑧------------------->|
;	                     ↑
;			　　 ●メンバーＤには強制休符は与えられない
;
;　(注)単独の“%”指定は“%ABCDEFGHIJKLMNOZ”の省略形と見なすことができます。
;
;　スコア譜のメンバーが多く、パート譜のメンバーが少ない場合、“%”に添えるメ
;　ンバーが増えて入力が煩雑になります。そのような場合は“%”の直後に“~”を添
;　えることで以降に記述するメンバーの意味を逆転させることができます。すなわち
;　タイミングを合せたくないメンバーのみを列挙すればよいことになります。
;
