	[KernelFunction, Description("アルペジオの記述方法")]
	public string Get2_22()
	{
		return """
;　ピアノの譜面によく見かける記号で、和音音符の左側に縦の波線が添えられたもの
;　があります。これはアルペジオ(分散和音)奏法の一種で、和音を同時に奏するので
;　はなく、多少ずらしながら奏でていく指定です。この奏法は、ギターの演奏ではそ
;　の楽器の特性上自然に発生するパターンです。このパターンを記述するために、和
;　音やコードの「発音遅延」指定があります。和音やコードの音長にコロンを添え、
;　その後にずらす音長を与えることで表現します。
```
	\+++ v100
	_4 [ml<dm>]2:32 _4 [<dml>]2:32 _4 [l<rf>]2:32 _4 [s<rm>]2:32 _1

	'G'1:64 'E7'2:64 'G7/D':64 'C'1:32 ,1:32 ,1:8. _1
```
;　発音遅延の順番は以下の通りです。
;　　・和音の発音遅延はその記述音順に従う。
;　　・コードの発音遅延は低音部から高音部に向けて起こる。
;
;　６４分音符よりも短い発音遅延をしたい場合は微分音長“i”を利用してください。
;　　→“(1-23) 最小分解能と微分音長”を参照のこと。
;
;　なお、コロンに添える遅延音長は、通常の省略音長と独立の省略が可能です。
;　よって一度定義すれば、後はコロンだけの記述で同様の発音遅延が起ります。
;　コロンを記述しない場合は、アルペジオが起らず通常の音長が再現されます。
```
	'F7-9/D'4:32 ,: ,: ,: _1
```
;　遅延音長の末尾にマイナス記号を添えることで、発音の順番を逆向きにすることが
;　できます。このマイナス記号による発音方向の切替えを利用すれば、ダウン・スト
;　ロークとアップ・ストロークを交互に繰り返すギターの奏法などを簡便に記述する
;　ことができます。
```
	'C'4:32 'C'4:32- 'C'4:32 'C'4:32- _2
	'C'4:32    ,:-      ,:      ,:-   _2	← 上記の省略記法
```
;　コードと和音を組合せて表記してもアルペジオや逆アルペジオを実現することがで
;　き、コードに音を追加していくことが可能です。なおアルペジオの発音順番は、和
;　音内の音符やコードの記述順に従います。
```
	'G7'1:16 _4
	　↓
	['G7'c<rf>]1:16 _4
	　↓
	[>>c<r<'G7'c<rf>]1:16 _2
```
;　(注)アルペジオの音長は、連符内においても連符比率でスケーリングされず、記述
;　　　された音長がそのまま採用されます。また、連符内や和音内で指定したアルペ
;　　　ジオ音長は通常の音長と同様のプロセスで継承され、そこで指定したアルペジ
;　　　オは連符や和音の外には省略継承されません。

""";
	}

